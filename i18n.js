/* 适用说明/库存备注是入库时按中文拼接的存量数据：显示时按语言翻译 */
function fitLang(s){
  if(!s||LANG==='zh') return s;
  return s
    .replace(/（原文品类[:：]\s*([^）]*)）?/g, ' ('+T('fn_origcat')+': $1)')
    .replace(/年份\s*/g, T('fn_years'))
    .replace(/每车\s*(\d+)\s*件/g, (m,n)=>T('fn_perveh').replace('{n}',n))
    .replace(/地区\s*/g, T('fn_region'))
    .replace(/互换[:：]/g, T('fn_alt'))
    .replace(/被替代[:：]/g, T('fn_sup'))
    .replace(/，现货/g, ', '+T('fn_stock')+' ')
    .replace(/，\$/g, ', $')
    .replace(/（/g,'(').replace(/）/g,')');
}
function stockLang(s){
  if(!s||LANG==='zh') return s;
  return s
    .replace(/主仓现货/g, T('fn_mainwh')+' '+T('fn_stock'))
    .replace(/主仓/g, T('fn_mainwh'))
    .replace(/其他仓/g, T('fn_otherwh'))
    .replace(/其他店/g, T('fn_otherstore'))
    .replace(/供应商/g, T('fn_supplier'))
    .replace(/现货/g, T('fn_stock'))
    .replace(/；/g, '; ');
}
